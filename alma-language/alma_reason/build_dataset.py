# -*- coding: utf-8 -*-
"""Build dataset.jsonl. Every label is stated with where it came from.

    python -m alma_reason.build_dataset

TWO CORPORA, AND THEY ARE NOT THE SAME KIND OF THING
----------------------------------------------------
`syl:*`   256 items, the complete space of categorical syllogisms. The label is
          generated by a rule engine that `syllogism.py::self_test` checks
          against the 24 medieval names, so it is certain. **The numbers in
          RESULTS.md come from here.**
`mach:*`  28 items, 14 disputes x 2 seatings. Hand-transcribed from memory,
          `verified: false` on every one. A demonstration, never a benchmark.
          See the warning at the top of `machloket.py`.

THE SPLIT
---------
Stratified 70/30 by label, `random.Random(SPLIT_SEED)`, so the same split comes
back every time and the test half is never trained on. With 24 valid moods out
of 256 that is ~17 valid in train and 7 in test — thin, and said so plainly
rather than smoothed over by quoting raw accuracy, which "always invalid"
already scores 90.6% on.

THE SEATING SWAP, for machloket
-------------------------------
Every dispute appears twice, once each way round, because in the source corpus
בית שמאי is always named first and "the second speaker wins" would score 13/14
without learning anything. Both seatings carry the same פסק, so seat order
becomes worthless and party identity is the only thing left to read.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

from .encoding import (Argument, FEATURE_SETS, encode_machloket,
                       encode_syllogism, machloket_feature_names,
                       syllogism_feature_names)
from .machloket import corpus as machloket_corpus
from .syllogism import all_syllogisms, self_test as syllogism_self_test

HERE = Path(__file__).parent
OUT = HERE / "dataset.jsonl"
SPLIT_SEED = 20260911
TEST_FRACTION = 0.30


def syllogism_corpus(feature_set: str = "raw") -> list[Argument]:
    syllogism_self_test()          # the labels are not trusted, they are checked
    return [encode_syllogism(s, feature_set) for s in all_syllogisms()]


def machloket_arguments() -> list[Argument]:
    out = []
    for m in machloket_corpus():
        for swap in (False, True):
            out.append(encode_machloket(m, swap))
    return out


def stratified_split(items: list[Argument], seed: int = SPLIT_SEED,
                     test_fraction: float = TEST_FRACTION, group: bool = True
                     ) -> tuple[list[Argument], list[Argument]]:
    """Same proportion of each verdict on both sides of the line, and no
    dispute on both sides at once.

    THE LEAK THIS CLOSES, found by running it. Every machloket is in the corpus
    twice, once each way round (see the header). Splitting item by item put the
    two seatings of one dispute on opposite sides of the line, so the "held-out"
    half was the training half with the chairs swapped. The first machloket run
    scored 96.9% balanced that way, and that number measured memory, not
    generalisation. Items are therefore grouped by `meta["dispute"]` — every
    seating of a dispute goes to the same side — and only then stratified.
    Syllogisms carry no `dispute` key and are unaffected: each of the 256 is its
    own group, so the split is byte-identical to before for them.
    """
    rng = random.Random(seed)
    groups: dict[str, list[Argument]] = {}
    for a in items:
        key = a.meta.get("dispute") if group else None
        groups.setdefault(key or a.id, []).append(a)

    by_label: dict[str, list[list[Argument]]] = {}
    for key in sorted(groups):
        g = groups[key]
        by_label.setdefault(g[0].winner, []).append(g)

    train, test = [], []
    for label in sorted(by_label):
        blocks = by_label[label]
        rng.shuffle(blocks)
        cut = int(round(len(blocks) * test_fraction))
        for b in blocks[:cut]:
            test += b
        for b in blocks[cut:]:
            train += b
    rng.shuffle(train)
    rng.shuffle(test)
    return train, test


def write(path: Path = OUT) -> dict:
    rows, counts = [], {}
    for fs in FEATURE_SETS:
        for a in syllogism_corpus(fs):
            d = a.to_json()
            d["corpus"] = "syllogism"
            d["feature_set"] = fs
            d["label_certain"] = True
            rows.append(d)
            counts[f"syllogism/{fs}"] = counts.get(f"syllogism/{fs}", 0) + 1
    for a in machloket_arguments():
        d = a.to_json()
        d["corpus"] = "machloket"
        d["feature_set"] = "machloket"
        d["label_certain"] = False        # hand-transcribed, unverified
        rows.append(d)
        counts["machloket"] = counts.get("machloket", 0) + 1

    with open(path, "w", encoding="utf-8") as fh:
        for d in rows:
            fh.write(json.dumps(d, ensure_ascii=False) + "\n")
    return counts


def load(path: Path = OUT, corpus: str = "syllogism",
         feature_set: str = "raw") -> list[Argument]:
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            d = json.loads(line)
            if d["corpus"] == corpus and d["feature_set"] == feature_set:
                out.append(Argument.from_json(d))
    return out


def feature_names(corpus: str = "syllogism", feature_set: str = "raw") -> list[str]:
    if corpus == "machloket":
        return machloket_feature_names(machloket_corpus())
    return syllogism_feature_names(feature_set)


if __name__ == "__main__":
    counts = write()
    print(f"wrote {OUT}")
    for k in sorted(counts):
        print(f"  {k:24s} {counts[k]:4d} items")
    print()
    for corpus, fs in (("syllogism", "raw"), ("syllogism", "distrib"),
                       ("machloket", "machloket")):
        items = load(corpus=corpus, feature_set=fs)
        tr, te = stratified_split(items)
        pos = sum(1 for a in items if a.winner == "M")
        names = feature_names(corpus, fs)
        print(f"{corpus}/{fs}: {len(items)} items, {len(names)} features, "
              f"{pos} מתרץ / {len(items)-pos} מקשן  ->  "
              f"train {len(tr)} ({sum(1 for a in tr if a.winner=='M')} מתרץ), "
              f"test {len(te)} ({sum(1 for a in te if a.winner=='M')} מתרץ)")
