def corpus() -> list[Machloket]:
    return list(CORPUS)


def self_test() -> None:
    ids = [m.id for m in CORPUS]
    assert len(ids) == len(set(ids)), "duplicate id"
    for m in CORPUS:
        assert m.psak in ("A", "B"), m.id
        assert m.source, m.id
        assert m.psak_rule, m.id
        assert m.verified is False, (
            f"{m.id} claims to be verified. Nothing in this file has been "
            f"checked against a printed text — see the header.")


if __name__ == "__main__":
    self_test()
    print(f"{len(CORPUS)} disputes, hand-transcribed, 0 verified against a text.")
    for m in CORPUS:
        who = m.seat_a if m.psak == "A" else m.seat_b
        print(f"  {m.id:28s} {m.source:28s} הלכה כ{who}")
