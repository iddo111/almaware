"""REAL machloket, hand-transcribed. Small on purpose, and honestly labelled.

⚠ READ THIS BEFORE USING ANY NUMBER FROM THIS FILE ⚠
-----------------------------------------------------
These disputes were written out **from memory** by the agent that built this
package, with the tractate and daf named for each. They have **NOT** been
checked against a printed text or against Sefaria. Nothing here is a
benchmark. It is a demonstration set: enough to show that the weave in
`weave.py` runs on a real Talmudic dispute and produces a מסקנה, and to ask
one narrow, checkable question —

    does the weave recover the recorded rule of פסק, הלכה כבית הלל,
    from examples alone, and what does it do with the one case where
    בית הלל themselves reversed and ruled like בית שמאי?

The real numbers in RESULTS.md come from `syllogism.py`, whose 256 labels are
generated by a rule engine that is itself checked against the 24 medieval
names. Those labels are certain. These are not, and are marked `verified=False`
one by one so no one can quote them by accident.

WHY THE LABEL IS NOT AN OPINION EVEN SO
---------------------------------------
The label here is the **פסק** — which side the halacha follows — and that is a
recorded fact with a stated reason, not the transcriber's judgement of who
argued better. Two rules of פסק cover almost everything below:

  * **הלכה כבית הלל** — עירובין יג ע"ב: *"יצתה בת קול ואמרה: אלו ואלו דברי
    אלהים חיים, והלכה כבית הלל."* Both are the living word; the law is Hillel.
  * **אחרי רבים להטות** — the majority, as רבי יהושע held against רבי אליעזר
    at תנור של עכנאי (בבא מציעא נט ע"ב), *"לא בשמים היא"*.

The one reversal (`gittin-half-slave`) is in the corpus deliberately. A rule
with no exception teaches nothing about when a rule stops.
"""
