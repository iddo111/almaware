#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""fontgen.py — generate src/font_hebrew.h : an 8x16 bitmap font (ASCII + Hebrew)
for ALMA-OS T-Deck, rendered from a free (SIL-OFL) Hebrew TTF.

Cell: 8 px wide x 16 px tall, 1 bit/pixel, MSB = leftmost pixel, 16 bytes/glyph.
Coverage: ASCII 0x20..0x7E (95 glyphs) + Hebrew U+05D0..U+05EA (27 glyphs)
          + geresh U+05F3, gershayim U+05F4  => 124 glyphs, 1984 bytes.

Usage:  python tools/fontgen.py            (writes src/font_hebrew.h)

לזכרה של עלמה ז"ל · ALMAWARE
"""
from __future__ import annotations
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "font_hebrew.h"

CELL_W, CELL_H = 8, 16

# Preference order: free/OFL Hebrew fonts first (licensing-clean), then system fallbacks.
FONT_CANDIDATES = [
    ("C:/Windows/Fonts/FrankRuhlHofshi-Regular.otf", "Frank Ruhl Hofshi (SIL-OFL)"),
    ("C:/Windows/Fonts/DavidLibre-Regular.ttf",      "David Libre (SIL-OFL)"),
    ("C:/Windows/Fonts/tahoma.ttf",                  "Tahoma (system fallback)"),
    ("C:/Windows/Fonts/arial.ttf",                   "Arial (system fallback)"),
]

CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0x05D0, 0x05EB)) + [0x05F3, 0x05F4]


def render_glyph(font, ch, size_img=48):
    """Render one char on a big canvas, return list of (x,y) set pixels + bbox."""
    img = Image.new("L", (size_img, size_img), 0)
    d = ImageDraw.Draw(img)
    d.text((size_img // 4, 4), ch, fill=255, font=font)
    return img


# Size is chosen so HEBREW + digits fit the cell; rare over-wide ASCII (W, M, @)
# get squeezed per-glyph instead of shrinking the whole font.
CRITICAL = list(range(0x05D0, 0x05EB)) + list(range(0x30, 0x3A)) + [0x41, 0x61]


def try_font(path, px):
    try:
        font = ImageFont.truetype(path, px)
    except Exception:
        return None
    max_w = max_h = 0
    for cp in CRITICAL:
        img = render_glyph(font, chr(cp))
        bbox = img.getbbox()
        if bbox:
            max_w = max(max_w, bbox[2] - bbox[0])
            max_h = max(max_h, bbox[3] - bbox[1])
    # also cap TOTAL height across all glyphs (descenders like g, ק must fit 16)
    for cp in (0x67, 0x71, 0x05E7, 0x05DA):    # g q ק ך
        img = render_glyph(font, chr(cp))
        bbox = img.getbbox()
        if bbox:
            max_h = max(max_h, bbox[3] - bbox[1])
    if max_w <= CELL_W and max_h <= CELL_H:
        return font
    return None


def pick_font():
    for path, label in FONT_CANDIDATES:
        if not Path(path).exists():
            continue
        for px in range(18, 7, -1):           # largest size whose ink fits 8x16
            f = try_font(path, px)
            if f:
                return f, label, px
    print("ERROR: no usable Hebrew font found", file=sys.stderr)
    sys.exit(1)


def glyph_bitmap(font, ch):
    """Return 16 row-bytes for ch, ink centered horizontally, baseline-aligned."""
    img = render_glyph(font, ch)
    bbox = img.getbbox()
    rows = [0] * CELL_H
    if not bbox:
        return rows                            # space etc.
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    if w > CELL_W or h > CELL_H:
        # squeeze over-wide/tall ink (W, M, @ ...) into the cell
        ink = img.crop(bbox).resize((min(w, CELL_W), min(h, CELL_H)), Image.LANCZOS)
        img = Image.new("L", img.size, 0)
        img.paste(ink, (x0, y0))
        x0, y0 = x0, y0
        x1, y1 = x0 + ink.width, y0 + ink.height
        w, h = ink.width, ink.height
        if y0 + h > 4 + CELL_H:                # keep inside vertical band
            y0 = max(0, 4 + CELL_H - h); y1 = y0 + h
            img2 = Image.new("L", img.size, 0)
            img2.paste(ink, (x0, y0)); img = img2
    # vertical: align all glyphs by a common top anchor = font ascent line.
    ascent, _ = font.getmetrics()
    # glyph drawn with text() at y=4, so its design top is 4; ink top is y0.
    # place ink so that (design ascent) maps near row CELL_H-4 baseline:
    top_in_cell = min(max(y0 - 4 + (CELL_H - (ascent if ascent <= CELL_H else CELL_H)) // 1, 0), CELL_H - h)
    top_in_cell = max(0, min(CELL_H - h, y0 - 4))   # keep the font's own vertical metric
    left_in_cell = (CELL_W - w) // 2
    px = img.load()
    for yy in range(h):
        byte = 0
        for xx in range(w):
            if px[x0 + xx, y0 + yy] > 64:      # threshold (64 keeps thin stems, e.g. ו)
                byte |= 0x80 >> (left_in_cell + xx)
        rows[top_in_cell + yy] = byte
    return rows


def main():
    font, label, px = pick_font()
    print(f"using {label} @ {px}px")
    lines = []
    lines.append("// font_hebrew.h — AUTO-GENERATED by tools/fontgen.py. Do not hand-edit.")
    lines.append(f"// Source typeface: {label} rendered at {px}px into 8x16 cells.")
    lines.append("// Bitmap fonts carry no code from the source font; OFL faces are free to use.")
    lines.append("// Coverage: ASCII 0x20-0x7E, Hebrew U+05D0-U+05EA, U+05F3, U+05F4.")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f"#define FONT_W {CELL_W}")
    lines.append(f"#define FONT_H {CELL_H}")
    lines.append(f"#define FONT_GLYPHS {len(CODEPOINTS)}")
    lines.append("")
    lines.append("// 16 bytes per glyph, top row first, MSB = leftmost pixel.")
    lines.append("static const uint8_t FONT8X16[FONT_GLYPHS][16] = {")
    for cp in CODEPOINTS:
        rows = glyph_bitmap(font, chr(cp))
        hexrows = ",".join(f"0x{b:02X}" for b in rows)
        name = chr(cp) if cp >= 0x20 and cp != 0x5C and cp != 0x7F else "?"
        lines.append(f"  {{{hexrows}}}, // U+{cp:04X} {name}")
    lines.append("};")
    lines.append("")
    lines.append("// Map a Unicode codepoint to a glyph index, or -1 if not covered.")
    lines.append("static inline int fontGlyphIndex(uint32_t cp) {")
    lines.append("  if (cp >= 0x20 && cp <= 0x7E)    return (int)(cp - 0x20);")
    lines.append("  if (cp >= 0x5D0 && cp <= 0x5EA)  return 95 + (int)(cp - 0x5D0);")
    lines.append("  if (cp == 0x5F3) return 122;  // geresh")
    lines.append("  if (cp == 0x5F4) return 123;  // gershayim")
    lines.append("  return -1;")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}  ({len(CODEPOINTS)} glyphs, {len(CODEPOINTS)*16} bytes)")


if __name__ == "__main__":
    main()
