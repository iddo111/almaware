#!/usr/bin/env bash
# install_linux.sh — Hebrew Mic installer for Linux (Ubuntu/Debian/Mint)
#
# WHAT THIS DOES:
#   1. apt-installs system deps: python3-venv, portaudio, xdotool, wmctrl, xclip
#   2. Creates a venv and pip-installs Python deps
#   3. Writes a ~/.local/share/applications/hebrew-mic.desktop launcher
#   4. Optionally installs a systemd --user service for always-on operation
#
# USAGE:
#   chmod +x packaging/install_linux.sh
#   bash packaging/install_linux.sh
#
#   # Skip apt (if you already have system deps):
#   bash packaging/install_linux.sh --no-apt
#
#   # Install systemd always-on service:
#   bash packaging/install_linux.sh --systemd
#
# NOTES:
#   - The app uses xdotool for keyboard injection. Under Wayland you may need to
#     install xdotool + set GDK_BACKEND=x11, or use a Wayland-native typer.
#   - Audio input requires PulseAudio or PipeWire (both work with sounddevice).
#   - On non-Debian distros (Arch, Fedora) replace apt commands with your package
#     manager equivalents (pacman, dnf). See README_CROSSPLATFORM.md for details.
#
# לזכרה של עלמה ז"ל — iddoperez.ai

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"    # .../voice-input
VENV="$ROOT/.venv-linux"
DESKTOP_DIR="${HOME}/.local/share/applications"
SYSTEMD_DIR="${HOME}/.config/systemd/user"

NO_APT=false
WITH_SYSTEMD=false
GPU=false

for arg in "$@"; do
    case "$arg" in
        --no-apt)    NO_APT=true ;;
        --systemd)   WITH_SYSTEMD=true ;;
        --gpu)       GPU=true ;;
    esac
done

echo_cyan()  { printf '\033[36m%s\033[0m\n' "$*"; }
echo_green() { printf '\033[32m%s\033[0m\n' "$*"; }
echo_yellow(){ printf '\033[33m%s\033[0m\n' "$*"; }

echo_cyan "[install_linux] Hebrew Mic — Linux installer"
echo_cyan "[install_linux] root: $ROOT"

# ── 1. System packages ─────────────────────────────────────────────────────────
if [ "$NO_APT" = false ]; then
    echo_cyan "[install_linux] Installing system packages (needs sudo) ..."
    sudo apt-get update -qq
    sudo apt-get install -y \
        python3 \
        python3-venv \
        python3-pip \
        portaudio19-dev \
        libportaudio2 \
        xdotool \
        wmctrl \
        xclip \
        xsel \
        libx11-dev \
        ffmpeg
    echo_green "[install_linux] System packages OK"
fi

# ── 2. Python venv ─────────────────────────────────────────────────────────────
echo_cyan "[install_linux] Creating venv at $VENV ..."
python3 -m venv "$VENV"
PY="$VENV/bin/python"
PIP="$VENV/bin/pip"

"$PIP" install --upgrade pip --quiet

REQ="$SCRIPT_DIR/requirements.txt"
if [ "$GPU" = true ]; then
    REQ="$SCRIPT_DIR/requirements-gpu.txt"
    echo_yellow "[install_linux] GPU mode: using requirements-gpu.txt"
fi

echo_cyan "[install_linux] Installing Python deps from $REQ ..."
"$PIP" install -r "$REQ"

# Linux-specific extras
"$PIP" install --quiet \
    pynput \
    python-xlib \
    ewmh

echo_green "[install_linux] Python deps installed"

# ── 3. Wrapper script ──────────────────────────────────────────────────────────
WRAPPER="$ROOT/start_mic_linux.sh"
cat > "$WRAPPER" << WRAPPER_EOF
#!/usr/bin/env bash
# start_mic_linux.sh — launch Hebrew Mic via venv (generated by install_linux.sh)
set -euo pipefail
ROOT="$ROOT"
VENV="$VENV"
cd "\$ROOT"
exec "\$VENV/bin/python" "\$ROOT/supervisor.py"
WRAPPER_EOF
chmod +x "$WRAPPER"
echo_green "[install_linux] Wrapper: $WRAPPER"

# ── 4. Desktop launcher (.desktop file) ───────────────────────────────────────
mkdir -p "$DESKTOP_DIR"
DESKTOP="$DESKTOP_DIR/hebrew-mic.desktop"
cat > "$DESKTOP" << DESKTOP_EOF
[Desktop Entry]
Type=Application
Name=Hebrew Mic
GenericName=Hebrew Voice Input
Comment=ALMAWARE always-on Hebrew voice-to-text dictation — לזכרה של עלמה ז"ל
Exec=$WRAPPER
Icon=microphone
Terminal=true
Categories=AudioVideo;Utility;
Keywords=hebrew;voice;dictation;mic;
StartupNotify=false
DESKTOP_EOF
chmod +x "$DESKTOP"
echo_green "[install_linux] Desktop launcher: $DESKTOP"
echo_yellow "[install_linux] Tip: run 'update-desktop-database $DESKTOP_DIR' to make it appear in app menus"

# ── 5. Optional systemd --user service ────────────────────────────────────────
if [ "$WITH_SYSTEMD" = true ]; then
    echo_cyan "[install_linux] Installing systemd --user service ..."
    mkdir -p "$SYSTEMD_DIR"
    SERVICE="$SYSTEMD_DIR/hebrew-mic.service"
    cat > "$SERVICE" << SERVICE_EOF
[Unit]
Description=ALMAWARE Hebrew Mic — always-on Hebrew voice dictation
Documentation=https://iddoperez.ai
After=graphical-session.target pulseaudio.service pipewire.service
Wants=graphical-session.target

[Service]
Type=simple
ExecStart=$WRAPPER
Restart=always
RestartSec=3
StandardOutput=append:$ROOT/history/supervisor-linux.log
StandardError=append:$ROOT/history/supervisor-linux.log
Environment=PYTHONIOENCODING=utf-8
Environment=PYTHONUNBUFFERED=1
# Wayland: uncomment next line if keyboard injection fails
# Environment=GDK_BACKEND=x11

[Install]
WantedBy=graphical-session.target
SERVICE_EOF

    systemctl --user daemon-reload
    systemctl --user enable hebrew-mic.service
    echo_green "[install_linux] Service installed and enabled."
    echo_yellow "[install_linux] Commands:"
    echo_yellow "   Start now  : systemctl --user start hebrew-mic"
    echo_yellow "   Stop       : systemctl --user stop hebrew-mic"
    echo_yellow "   Status     : systemctl --user status hebrew-mic"
    echo_yellow "   Logs       : journalctl --user -u hebrew-mic -f"
    echo_yellow "   Disable    : systemctl --user disable hebrew-mic"
else
    echo_yellow "[install_linux] Tip: re-run with --systemd to install an always-on user service"
fi

# ── 6. Quick smoke-test ────────────────────────────────────────────────────────
echo_cyan "[install_linux] Smoke-testing import chain ..."
"$PY" -c "import sounddevice, numpy, faster_whisper; print('imports OK')"

echo_cyan ""
echo_cyan "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo_green " Hebrew Mic — Linux install complete"
echo_green "   venv    : $VENV"
echo_green "   launcher: $WRAPPER"
echo_green "   desktop : $DESKTOP"
echo_cyan  " לזכרה של עלמה ז\"ל — iddoperez.ai"
echo_cyan  "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
