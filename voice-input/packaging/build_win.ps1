# build_win.ps1 - Windows installer + optional PyInstaller spec for Hebrew Mic
#
# WHAT THIS DOES:
#   1. Creates a Python venv in voice-input\.venv
#   2. pip-installs all requirements (CPU by default; pass -GPU for CUDA)
#   3. Registers a Windows Scheduled Task "ALMAWARE-HebMic-Diamond" that runs
#      start_mic_diamond.bat at logon (same as install-task.ps1 but wraps venv).
#
# HONEST NOTE ON "COMPILING TO AN EXE":
#   PyInstaller can bundle the Hebrew Mic into a single executable, but
#   faster-whisper + ctranslate2 + (optionally) CUDA produce a 1-3 GB bundle
#   that is slow to start, prone to DLL conflicts, and hard to update.
#   The RECOMMENDED approach is the venv-install here + start_mic_diamond.bat.
#   A best-effort mic_win.spec is generated at the end for those who insist on
#   an exe, but it is NOT the primary delivery mechanism.
#
# USAGE:
#   # From an elevated PowerShell:
#   cd D:\CLAUDE\voice-input
#   powershell -ExecutionPolicy Bypass -File packaging\build_win.ps1
#
#   # For CUDA GPU support:
#   powershell -ExecutionPolicy Bypass -File packaging\build_win.ps1 -GPU
#
# לזכרה של עלמה ז"ל - iddoperez.ai

param(
    [switch]$GPU,
    [switch]$SkipTask,
    [string]$PythonExe = ""
)

$ErrorActionPreference = "Stop"

$HERE = Split-Path -Parent $MyInvocation.MyCommand.Path
$ROOT = Split-Path -Parent $HERE    # D:\CLAUDE\voice-input

Write-Host "[build_win] Hebrew Mic — Windows installer" -ForegroundColor Cyan
Write-Host "[build_win] root: $ROOT"

# ── 1. Resolve Python ─────────────────────────────────────────────────────────
if ($PythonExe -eq "") {
    # Try common locations in priority order
    $candidates = @(
        "python",
        "py",
        "C:\Users\$env:USERNAME\AppData\Local\Programs\Python\Python312\python.exe",
        "C:\Users\$env:USERNAME\AppData\Local\Programs\Python\Python311\python.exe",
        "C:\Python312\python.exe",
        "C:\Python311\python.exe"
    )
    foreach ($c in $candidates) {
        try {
            $ver = & $c --version 2>&1
            if ($LASTEXITCODE -eq 0) { $PythonExe = $c; break }
        } catch {}
    }
}
if ($PythonExe -eq "") {
    Write-Error "Python not found. Install Python 3.10-3.12 and retry, or pass -PythonExe path\to\python.exe"
    exit 1
}
$pyVer = & $PythonExe --version
Write-Host "[build_win] Using Python: $PythonExe ($pyVer)" -ForegroundColor Green

# ── 2. Create venv ────────────────────────────────────────────────────────────
$VENV = Join-Path $ROOT ".venv"
if (-not (Test-Path "$VENV\Scripts\python.exe")) {
    Write-Host "[build_win] Creating venv at $VENV ..."
    & $PythonExe -m venv $VENV
    if ($LASTEXITCODE -ne 0) { Write-Error "venv creation failed"; exit 1 }
} else {
    Write-Host "[build_win] venv exists at $VENV — skipping creation"
}
$VENV_PY = "$VENV\Scripts\python.exe"

# ── 3. Upgrade pip + install requirements ─────────────────────────────────────
Write-Host "[build_win] Upgrading pip ..."
& $VENV_PY -m pip install --upgrade pip --quiet

$REQ = if ($GPU) {
    Join-Path $HERE "requirements-gpu.txt"
} else {
    Join-Path $HERE "requirements.txt"
}
Write-Host "[build_win] Installing from: $REQ"
& $VENV_PY -m pip install -r $REQ
if ($LASTEXITCODE -ne 0) { Write-Error "pip install failed"; exit 1 }
Write-Host "[build_win] Requirements installed." -ForegroundColor Green

# ── 4. Generate a launcher .bat that uses the venv ───────────────────────────
$LAUNCHER = Join-Path $ROOT "start_mic_venv.bat"
@"
@echo off
REM start_mic_venv.bat - launch Hebrew Mic via the .venv created by build_win.ps1
REM Generated by packaging\build_win.ps1
setlocal
set "DIR=$ROOT"
set "VENV_PY=$VENV\Scripts\python.exe"
cd /d "%DIR%"
echo [start_mic_venv] starting diamond watchdog via venv...
"%VENV_PY%" "%DIR%\supervisor.py"
echo [start_mic_venv] supervisor exited (rc=%errorlevel%)
pause
endlocal
"@ | Set-Content -Path $LAUNCHER -Encoding UTF8
Write-Host "[build_win] Launcher written: $LAUNCHER" -ForegroundColor Green

# ── 5. Register Scheduled Task ────────────────────────────────────────────────
if (-not $SkipTask) {
    Write-Host "[build_win] Registering Scheduled Task 'ALMAWARE-HebMic-Diamond' ..."
    try {
        $action   = New-ScheduledTaskAction `
                      -Execute $LAUNCHER `
                      -WorkingDirectory $ROOT
        $trigger  = New-ScheduledTaskTrigger -AtLogOn
        $settings = New-ScheduledTaskSettingsSet `
                      -AllowStartIfOnBatteries `
                      -DontStopIfGoingOnBatteries `
                      -StartWhenAvailable `
                      -ExecutionTimeLimit ([TimeSpan]::Zero)
        $principal = New-ScheduledTaskPrincipal `
                      -UserId $env:USERNAME `
                      -LogonType Interactive `
                      -RunLevel Highest
        Register-ScheduledTask `
          -TaskName "ALMAWARE-HebMic-Diamond" `
          -Action $action -Trigger $trigger `
          -Settings $settings -Principal $principal `
          -Force `
          -Description "Hebrew Mic (ALMAWARE) — diamond always-on watchdog via .venv."
        Write-Host "[build_win] Task registered. The mic will start automatically at next logon." -ForegroundColor Green
        Write-Host "[build_win] To start immediately:  Start-ScheduledTask -TaskName 'ALMAWARE-HebMic-Diamond'"
        Write-Host "[build_win] To remove:             Unregister-ScheduledTask -TaskName 'ALMAWARE-HebMic-Diamond' -Confirm:`$false"
    } catch {
        Write-Warning "Scheduled Task registration failed (is this PowerShell elevated?): $_"
        Write-Host "Tip: right-click PowerShell -> 'Run as administrator' and retry."
    }
} else {
    Write-Host "[build_win] -SkipTask specified — no Scheduled Task registered."
}

# ── 6. Generate best-effort PyInstaller spec ──────────────────────────────────
Write-Host "[build_win] Generating mic_win.spec (best-effort, see HONEST NOTES inside) ..."
$SPEC = Join-Path $HERE "mic_win.spec"
@"
# mic_win.spec - PyInstaller spec for Hebrew Mic (BEST-EFFORT)
# Generated by packaging\build_win.ps1
#
# ╔══════════════════════════════════════════════════════════════════════════════╗
# ║  HONEST NOTES — READ BEFORE SPENDING TIME ON THIS                          ║
# ║                                                                              ║
# ║  Bundling faster-whisper + ctranslate2 + CUDA into a single .exe is:        ║
# ║    • HEAVY  : the bundle is typically 1-3 GB (model weights alone are 1 GB) ║
# ║    • FRAGILE: ctranslate2/CUDA use hand-rolled DLL loading that PyInstaller  ║
# ║               cannot reliably detect; expect missing-DLL errors at runtime.  ║
# ║    • SLOW   : cold-start of a frozen exe is significantly slower than venv.  ║
# ║    • STALE  : every model update means a full re-bundle + re-distribute.     ║
# ║                                                                              ║
# ║  RECOMMENDED APPROACH (much simpler, same UX for end-users):                ║
# ║    1. Run  packaging\build_win.ps1  (creates .venv + Scheduled Task)        ║
# ║    2. Users double-click  start_mic_diamond.bat  or  start_mic_venv.bat     ║
# ║    3. Task auto-starts on logon — it's effectively the same as a compiled    ║
# ║       app from the user's perspective.                                       ║
# ║                                                                              ║
# ║  If you still want the .exe, install PyInstaller in the venv:               ║
# ║    .venv\Scripts\pip install pyinstaller                                     ║
# ║  Then:                                                                       ║
# ║    cd D:\CLAUDE\voice-input                                                 ║
# ║    .venv\Scripts\pyinstaller packaging\mic_win.spec                         ║
# ║  and expect to iterate on hidden imports / missing DLLs.                    ║
# ╚══════════════════════════════════════════════════════════════════════════════╝

import os, sys
from PyInstaller.utils.hooks import collect_data_files, collect_dynamic_libs

block_cipher = None

# Gather ctranslate2 native libs (the main source of bundle failures)
ct2_datas   = collect_data_files('ctranslate2')
ct2_binaries = collect_dynamic_libs('ctranslate2')

a = Analysis(
    ['../voice_input.py'],
    pathex=['..'],
    binaries=ct2_binaries,
    datas=[
        ('../config.json',    '.'),
        ('../*.py',           '.'),
        *ct2_datas,
    ],
    hiddenimports=[
        'sounddevice', 'numpy', 'keyboard', 'pyperclip',
        'faster_whisper', 'ctranslate2',
        # smart-engine extras — comment out if not installed:
        # 'corrector', 'iqbrainz', 'learner',
    ],
    hookspath=[],
    hooksconfig={},
    runtime_hooks=[],
    excludes=[],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='hebrew_mic',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,         # UPX often breaks CUDA DLLs — leave False
    console=True,      # keep console for logging output
    disable_windowed_traceback=False,
    argv_emulation=False,
    icon=None,         # add an .ico file path here if desired
)

coll = COLLECT(
    exe,
    a.binaries,
    a.zipfiles,
    a.datas,
    strip=False,
    upx=False,
    upx_exclude=[],
    name='hebrew_mic',
)

# NOTE: The model weights (~1 GB for ivrit-ai/whisper-large-v3-turbo-ct2) are
# downloaded by faster-whisper at runtime to ~/.cache/huggingface/hub/
# To bundle them into the exe folder, copy them manually into the dist/ tree and
# point config.json model at the local path instead of the HF model ID.
"@ | Set-Content -Path $SPEC -Encoding UTF8
Write-Host "[build_win] Spec written: $SPEC" -ForegroundColor Green

Write-Host ""
Write-Host "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━" -ForegroundColor Cyan
Write-Host " Hebrew Mic — Windows install complete" -ForegroundColor Cyan
Write-Host "   venv    : $VENV" -ForegroundColor Green
Write-Host "   launcher: $LAUNCHER" -ForegroundColor Green
Write-Host "   spec    : $SPEC  (best-effort; see notes inside)" -ForegroundColor Yellow
Write-Host "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━" -ForegroundColor Cyan
Write-Host " לזכרה של עלמה ז\"ל — iddoperez.ai" -ForegroundColor Magenta
