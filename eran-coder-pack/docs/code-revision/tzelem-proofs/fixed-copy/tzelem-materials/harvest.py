def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    os.makedirs(MATS, exist_ok=True)
    manifest = []
    for r in RECIPE:
        m = harvest(**r)
        stem = os.path.join(MATS, m.name)
        p = write_tzm(stem, m)
        n = os.path.getsize(p)
        manifest.append({"name": m.name, "kind": m.kind, "file": os.path.basename(p),
                         "bytes": n, "texels": int(m.albedo.shape[0]),
                         "mm_per_texel": m.mm_per_texel,
                         "physical_size_mm": m.meta["physical_size_mm"],
                         "scale_basis": m.meta["scale_basis"],
                         **{k: m.meta[k] for k in ("source", "source_crop_xyxy",
                                                   "provenance", "licence")}})
        print(f"{m.name:18s} {m.albedo.shape[0]:4d}px  "
              f"{m.mm_per_texel*1000:7.1f} um/texel  "
              f"{m.meta['physical_size_mm']:7.1f} mm across  "
              f"[{m.meta['scale_basis']:9s}]  {n/1e6:5.2f} MB  <- {r['frame']}")
    with open(os.path.join(MATS, "MANIFEST.json"), "w", encoding="utf-8") as fh:
        json.dump({"harvested": manifest,
                   "all_from": "Iddo's own footage, room3d/room_20260905.mp4",
                   "third_party_assets": [],
                   "calibration": "calibrate.py -> 5.9639 px/mm on the f0008 desk "
                                  "plane, +/-2.2% vs the printed digits"},
                  fh, indent=1, ensure_ascii=False)
    print(f"\nwrote {len(manifest)} materials + MANIFEST.json to {MATS}")


if __name__ == "__main__":
    main()
