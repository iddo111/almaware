# ------------------------------------------------------------------ small tools

def srgb_to_linear(x: np.ndarray) -> np.ndarray:
    return np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)


def linear_to_srgb(x: np.ndarray) -> np.ndarray:
    x = np.clip(x, 0.0, 1.0)
    return np.where(x <= 0.0031308, x * 12.92, 1.055 * x ** (1 / 2.4) - 0.055)


def box_blur(a: np.ndarray, r: int, wrap: bool = False) -> np.ndarray:
    """Separable box blur, two passes ~ a Gaussian.

    `wrap=True` pads by WRAPPING instead of clamping, and it is not a nicety: the
    first version clamped everywhere, so every map DERIVED from the tileable
    albedo (roughness, ao, height) had its own fresh seam baked back in by the
    blur. `test_material.py`'s wrap check caught it at a seam/interior ratio of
    11.2 on roughness while albedo and normal sat at 1.2-1.7.
    """
    if r < 1:
        return a.copy()
    out = a
    mode = "wrap" if wrap else "edge"
    for _ in range(2):
        pad = np.pad(out, [(r, r), (r, r)] + [(0, 0)] * (out.ndim - 2), mode=mode)
        c = np.cumsum(pad, axis=0)
        out = (c[2 * r:] - c[:-2 * r]) / (2 * r)
        c = np.cumsum(out, axis=1)
        out = (c[:, 2 * r:] - c[:, :-2 * r]) / (2 * r)
    return out


def make_tileable(a: np.ndarray, band_frac: float = 0.14) -> np.ndarray:
    """PERIODIC-PLUS-SMOOTH (Moisan 2011). The seam leaves; the picture stays.

    THE FIRST VERSION WAS WRONG AND THE PICTURES SHOWED IT. It rolled the patch by
    half and cross-faded, which is the recipe every texture tutorial gives — and
    every harvested albedo came out as visible RECTANGULAR PATCHWORK, because a
    rolled copy has its OWN discontinuity and the fade only moves the seam, it
    does not remove it. Opening `mats.jpg` and looking at it is what caught this;
    the wrap test had passed, because a patchwork of four quadrants wraps
    perfectly at its border.

    Moisan's decomposition splits an image into u = p + s where s is the smooth
    component that carries the whole boundary jump and p is EXACTLY periodic. It
    is closed-form, it is two FFTs, and it removes only a very-low-frequency ramp
    — so the grain, the scratches and the stains are all still the photograph.

    `band_frac` is kept in the signature and ignored, so callers do not break.
    """
    if a.ndim == 3:
        return np.stack([make_tileable(a[..., k]) for k in range(a.shape[2])], axis=2)
    u = np.asarray(a, dtype=np.float64)
    h, w = u.shape
    v = np.zeros_like(u)
    v[0, :] = u[-1, :] - u[0, :]
    v[-1, :] = u[0, :] - u[-1, :]
    v[:, 0] += u[:, -1] - u[:, 0]
    v[:, -1] += u[:, 0] - u[:, -1]
    fy = 2.0 * np.cos(2.0 * np.pi * np.arange(h) / h)[:, None]
    fx = 2.0 * np.cos(2.0 * np.pi * np.arange(w) / w)[None, :]
    den = fy + fx - 4.0
    den[0, 0] = 1.0
    S = np.fft.fft2(v) / den
    S[0, 0] = 0.0
    smooth = np.real(np.fft.ifft2(S))
    p = u - smooth
    # put the mean back: the periodic component has the same mean as u by
    # construction, but clip the result into a sane range for a reflectance.
    return np.clip(p, 0.0, 4.0)


# ---------------------------------------------------------------- the harvester

def harvest(frame: str, crop, name: str, kind: str, mm_per_px: float,
            scale_basis: str, rough_base: float, metallic: float,
            size: int = 512, relief_mm: float = 0.35) -> Material:
    """One photograph of one surface -> one PBR material at a real size."""
    path = os.path.join(FRAMES, frame)
    if (crop[2] - crop[0]) != (crop[3] - crop[1]):
        # BROKEN WINDOWS. The first pass took a 512x70 strip of the steel rule and
        # squashed it into a 256x256 material: every feature stretched 3.7x along
        # one axis and `physical_size_mm` reported the width for both. A material
        # with two different scales in it is not a material.
        raise ValueError(f"{name}: crop {crop} is not square "
                         f"({crop[2]-crop[0]}x{crop[3]-crop[1]}) - a non-square "
                         f"crop resampled to a square map is anisotropically wrong")
    with Image.open(path) as im:
        sub = im.crop(crop).convert("RGB")
        src_px = sub.size
        if sub.size != (size, size):
            sub = sub.resize((size, size), Image.LANCZOS)
    srgb = np.asarray(sub, dtype=np.float64) / 255.0
    lin = srgb_to_linear(srgb)

    # mm per texel AFTER the resize (the crop is resampled to `size`)
    mm_per_texel = mm_per_px * (src_px[0] / size)

    # ---- FLAT FIELD: divide out the light, keep the surface -----------------
    # radius is a quarter of the patch, so anything larger than ~20 mm of gradient
    # is treated as illumination and anything finer is treated as the material.
    big = box_blur(lin, max(4, size // 8))
    flat = lin / np.maximum(big, 1e-4) * big.mean(axis=(0, 1))
    flat = np.clip(flat, 0.0, 4.0)

    flat = make_tileable(flat)

    # ---- ALBEDO: PER-CHANNEL mean-normalised, so it is DETAIL and nothing else
    # The first version divided all three channels by the SCALAR mean of the three,
    # which left the patch's own colour cast in the map. Multiplied into the room's
    # authored tint that double-counts the hue: the pegboard came back visibly more
    # orange in arm C than in arm A, and part of the Laplacian gain was that shift
    # rather than any structure. I saw it by putting the two crops side by side.
    # Per channel, the detail multiplier has mean (1,1,1) exactly, so the room's
    # palette is untouched and only STRUCTURE is added -- including the material's
    # own hue VARIATION, which survives; only the constant cast is removed.
    mean = flat.mean(axis=(0, 1))
    alb = flat / np.maximum(mean, 1e-6)[None, None, :]
    alb_u8 = np.clip(linear_to_srgb(np.clip(alb / 2.0, 0, 1)) * 255.0,
                     0, 255).astype(np.uint8)      # /2 so 1.0 sits mid-range

    # ---- HEIGHT: high-passed luminance -------------------------------------
    lum = (0.2126 * flat[..., 0] + 0.7152 * flat[..., 1] + 0.0722 * flat[..., 2])
    hp = lum - box_blur(lum, max(2, size // 32), wrap=True)
    sd = hp.std()
    hgt = np.clip(0.5 + hp / max(6.0 * sd, 1e-6), 0.0, 1.0)

    # ---- NORMAL from height, in REAL millimetres ---------------------------
    # relief_mm is the peak-to-peak depth this surface's luminance stands for.
    z = (hgt - 0.5) * relief_mm                       # mm
    # central difference by ROLL, so the slope is continuous across the wrap too
    dzdx = (np.roll(z, -1, axis=1) - np.roll(z, 1, axis=1)) / (2.0 * mm_per_texel)
    dzdy = (np.roll(z, -1, axis=0) - np.roll(z, 1, axis=0)) / (2.0 * mm_per_texel)
    nx, ny, nz = -dzdx, -dzdy, np.ones_like(z)
    ln = np.sqrt(nx * nx + ny * ny + nz * nz)
    nrm = np.stack([nx / ln, ny / ln, nz / ln], axis=2)
    nrm_u8 = np.clip((nrm * 0.5 + 0.5) * 255.0, 0, 255).astype(np.uint8)

    # ---- ROUGHNESS: authored base, measured modulation ---------------------
    micro = box_blur(np.abs(hp), max(2, size // 64), wrap=True)
    micro = micro / max(micro.mean(), 1e-9)           # 1.0 = this patch's average
    rough = np.clip(rough_base * (0.72 + 0.28 * micro), 0.02, 1.0)

    # ---- AO: a cavity map off the height -----------------------------------
    cav = box_blur(hgt, max(3, size // 24), wrap=True) - hgt
    ao = np.clip(1.0 - 1.6 * np.clip(cav, 0.0, 1.0), 0.0, 1.0)

    return Material(
        name=name, kind=kind,
        albedo=alb_u8,
        normal=nrm_u8,
        roughness=np.clip(rough * 255, 0, 255).astype(np.uint8),
        metallic=np.full((size, size), int(round(metallic * 255)), dtype=np.uint8),
        ao=np.clip(ao * 255, 0, 255).astype(np.uint8),
        height=np.clip(hgt * 255, 0, 255).astype(np.uint8),
        mm_per_texel=float(mm_per_texel),
        meta={
            "source": f"room3d/frames/{frame}",
            "source_crop_xyxy": list(crop),
            "source_px": list(src_px),
            "provenance": "Iddo Perez, room_20260905.mp4, filmed 2026-09-05, his own desk",
            "licence": "Iddo's own footage - no third-party licence",
            "scale_basis": scale_basis,
            "mm_per_px_source": float(mm_per_px),
            "physical_size_mm": float(mm_per_texel * size),
            "roughness_base_authored": float(rough_base),
            "metallic_authored": float(metallic),
            "relief_mm_authored": float(relief_mm),
            "albedo_is": "mean-normalised DETAIL, stored as sRGB with 1.0 at mid-grey",
            "measured": ["albedo", "scale" if scale_basis == "measured" else "-"],
            "derived": ["height", "normal", "roughness-variation", "ao"],
            "authored": ["roughness-base", "metallic", "relief_mm"],
        })


