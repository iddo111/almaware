static_assert(sizeof(kAccelData) == requiredBytes(52, 12), "accelerometer bitmap size");
static_assert(sizeof(kButtonsData) == requiredBytes(67, 12), "buttons bitmap size");

inline bool pixel(const Bitmap& bitmap, std::uint16_t x, std::uint16_t y) {
  const std::size_t bitIndex = static_cast<std::size_t>(y) * bitmap.width + x;
  return (bitmap.data[bitIndex / 8U] &
          static_cast<std::uint8_t>(0x80U >> (bitIndex % 8U))) != 0U;
}

